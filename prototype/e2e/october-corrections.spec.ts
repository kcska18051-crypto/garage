test('proposal uses selected quantities, print works and credit is a demo', async ({ page }) => {
  await page.goto('/cart')
  await page.getByTestId('cart-line').first().getByRole('button', { name: 'Увеличить количество' }).click()
  await page.getByRole('button', { name: 'Коммерческое предложение', exact: true }).click()
  const proposal = page.getByRole('dialog', { name: 'Коммерческое предложение' })
  await expect(proposal.locator('tbody tr')).toHaveCount(2)
  await page.evaluate(() => { window.print = () => { document.documentElement.dataset.printed = 'true' } })
  await proposal.getByRole('button', { name: 'Печать / сохранить PDF' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-printed','true')
  await page.getByRole('button', { name: 'Закрыть коммерческое предложение' }).click()
  await page.getByRole('button', { name: 'Купить в кредит', exact: true }).click()
  const credit = page.getByRole('dialog', { name: 'Купить в кредит' })
  await credit.getByLabel('Имя', { exact: true }).fill('Демо')
  await credit.getByLabel('Телефон', { exact: true }).fill('+7 900 000-00-00')
  await credit.getByRole('checkbox').check()
  await credit.getByRole('button', { name: 'Подготовить заявку' }).click()
  await expect(credit.getByRole('status')).toContainText('В банк ничего не отправлено')
})

