import { expect, test } from '@playwright/test'

for (const width of [360,390,1440,1920]) {
  test.describe(`contacts ${width}`, () => {
    test.use({ viewport: { width, height: 900 }, hasTouch: width < 600 })
    test('city, cards, map and local details preserve checkout and navigation', async ({ page }) => {
      await page.route('https://tile.openstreetmap.org/**', route => route.abort())
      await page.goto('/checkout/review')
      await page.getByLabel('Город самовывоза').selectOption('Вологда')
      await page.getByRole('radio', { name: /Демо-пункт выдачи/ }).check()
      await page.getByLabel('Комментарий к заказу').fill('Сохранённый заказ')
      const saved = await page.evaluate(() => localStorage.getItem('garage-checkout-v2'))
      await page.evaluate(() => scrollTo(0,0))
      await page.getByRole('button', { name: 'Выбрать город', exact: true }).click()
      await page.getByRole('button', { name: 'Вологда', exact: true }).click()
      await page.getByRole('contentinfo').getByRole('link', { name: 'Контакты', exact: true }).click()
      const cityTabs = page.getByRole('tablist', { name: 'Город контактов' })
      await expect(cityTabs.getByRole('tab')).toHaveCount(3)
      await expect(page.getByRole('tab', { name: 'Вологда', exact: true })).toHaveAttribute('aria-selected','true')
      await expect(page.locator('.contacts-locations select')).toHaveCount(0)
      await expect(page.getByText(/Город сайта:/)).toHaveCount(0)
      for (const tab of await cityTabs.getByRole('tab').all()) {
        await expect(tab).toBeVisible()
        expect(await tab.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
      }
      expect(await cityTabs.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
      const url = page.url()
      for (const [city, name, id] of [['Ярославль','Демо-магазин','store'],['Вологда','Демо-пункт выдачи','pickup'],['Череповец','Демо-сервисная точка','service']]) {
        await page.getByRole('tab', { name: city, exact: true }).click()
        await expect(page.getByRole('tab', { name: city, exact: true })).toHaveAttribute('aria-selected','true')
        await page.evaluate(() => scrollTo(0,0))
        await expect(page.getByRole('button', { name: 'Выбрать город', exact: true })).toContainText(city)
        await expect(page.getByTestId('contact-point')).toHaveCount(1)
        const radio = page.getByRole('radio', { name: new RegExp(name) })
        if (width < 600) await page.getByTestId('contact-point').locator('strong').tap()
        else { await radio.focus(); await page.keyboard.press('Space') }
        await expect(radio).toBeChecked()
        const marker = page.getByRole('button', { name: `На карте: ${name}` })
        await marker.focus(); await page.keyboard.press('Enter')
        await expect(marker).toHaveAttribute('aria-pressed','true')
        await expect(marker).toHaveAttribute('transform','translate(384 192)')
        await expect(page.getByRole('region', { name: 'Карта контактных точек' })).toContainText(name)
        const card = page.getByTestId('contact-point')
        await expect(card.locator('a[href^="tel:"]')).toHaveCount(1)
        await expect(card.locator('a[href^="mailto:"]')).toHaveCount(1)
        await expect(card.getByRole('link', { name: /О магазине|Подробнее/ })).toHaveCount(0)
        const trigger = card.getByRole('button', { name: `Фото и как добраться: ${name}` })
        await trigger.scrollIntoViewIfNeeded()
        const scroll = await page.evaluate(() => scrollY)
        await trigger.click()
        const panel = page.getByRole('dialog', { name: new RegExp(name) })
        const close = panel.getByRole('button', { name: 'Закрыть информацию о пункте' })
        await expect(close).toBeFocused()
        await expect(panel).toContainText(city)
        await expect(panel).toContainText('Демонстрационные данные')
        await expect(panel.locator('a[href^="tel:"]')).toHaveCount(1)
        await expect(panel.locator('a[href^="mailto:"]')).toHaveCount(1)
        await expect(panel.getByRole('link', { name: /Построить маршрут/ })).toHaveAttribute('target','_blank')
        await expect(panel.getByRole('link', { name: /Построить маршрут/ })).toHaveAttribute('href', /openstreetmap.org\/directions\?to=/)
        await expect(page).toHaveURL(url)
        expect(await panel.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
        if (id === 'store') await page.screenshot({ path: `artifacts/contacts-panel-${width}.png` })
        await page.keyboard.press('Shift+Tab')
        expect(await panel.evaluate(el => el.contains(document.activeElement))).toBe(true)
        await page.keyboard.press('Escape')
        await expect(panel).toHaveCount(0)
        await expect(trigger).toBeFocused()
        expect(Math.abs(await page.evaluate(() => scrollY) - scroll)).toBeLessThan(3)
        await expect(radio).toBeChecked()
        expect(await page.evaluate(() => localStorage.getItem('garage-checkout-v2'))).toBe(saved)
      }
      // Change the shared city in the header while staying on Contacts.
      await page.evaluate(() => scrollTo(0,0))
      await page.getByRole('button', { name: 'Выбрать город', exact: true }).click()
      await page.getByRole('button', { name: 'Ярославль', exact: true }).click()
      await expect(page.getByRole('tab', { name: 'Ярославль', exact: true })).toHaveAttribute('aria-selected','true')
      await expect(page.getByRole('radio', { name: /Демо-магазин/ })).toBeChecked()
      expect(await page.evaluate(() => localStorage.getItem('garage-checkout-v2'))).toBe(saved)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await cityTabs.scrollIntoViewIfNeeded()
      await page.getByRole('tab', { name: 'Ярославль', exact: true }).focus()
      await page.keyboard.press('ArrowRight')
      await expect(page.getByRole('tab', { name: 'Вологда', exact: true })).toBeFocused()
      await page.keyboard.press('Home')
      await page.screenshot({ path: `artifacts/contacts-page-${width}.png` })
      await page.goto('/checkout/review')
      await expect(page.getByLabel('Город самовывоза')).toHaveValue('Вологда')
      await expect(page.getByRole('radio', { name: /Демо-пункт выдачи/ })).toBeChecked()
      await expect(page.getByLabel('Комментарий к заказу')).toHaveValue('Сохранённый заказ')
    })
  })
}
