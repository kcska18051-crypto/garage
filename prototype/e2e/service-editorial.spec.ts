import {test,expect} from '@playwright/test'
for(const width of [1440,390,320])test(`service editorial reading and request at ${width}`,async({page})=>{
 await page.setViewportSize({width,height:900})
 await page.route('**/garage/style-check/**',route=>route.continue({url:route.request().url().replace('/garage/style-check/','/style-check/')}))
 await page.addInitScript(()=>localStorage.setItem('garage-cookie-preference',JSON.stringify({version:2,choice:'necessary'})))
 await page.goto('/services/service-center/pressure-washer-hoses')
 const main=page.getByRole('main')
 await expect(main.getByRole('heading',{level:1})).toHaveText('Изготовление шлангов высокого давления для моек')
 await expect(main.locator('tbody tr')).toHaveCount(10)
 await page.evaluate(()=>document.fonts.ready)
 for(const image of await main.locator('img').all())await expect.poll(()=>image.evaluate((e:HTMLImageElement)=>e.complete&&e.naturalWidth>0)).toBe(true)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 if(width<768)await expect(main.locator('.service-editorial-hero__visual img')).toHaveCSS('height','180px')
 await main.screenshot({path:`C:/Users/Admin/garage-audit/hose-${width}.png`})
 await main.getByRole('link',{name:'Рассчитать стоимость',exact:true}).click()
 await expect(page).toHaveURL(/item=pressure-washer-hoses/)
 await expect(page.getByRole('region',{name:'Заявка на изготовление шланга'})).toBeVisible()
 await expect(page.getByLabel('Модель мойки',{exact:true})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.getByRole('link',{name:'Вернуться к услуге'}).click()
 await expect(main.getByRole('heading',{level:1})).toBeVisible()
 await main.getByRole('link',{name:'Посмотреть цены'}).click()
 await expect(main.getByRole('table')).toBeVisible()
})
