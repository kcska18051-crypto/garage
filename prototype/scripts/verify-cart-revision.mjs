import assert from 'node:assert/strict'

export async function verifyCartRevision(browser, { base, width, screenshotRoot, expectedAsset }) {
  const context = await browser.newContext({ viewport: { width, height: 1000 }, hasTouch: width < 600, isMobile: width < 600 })
  const seed = [{ id: 'product-1', quantity: 1 }, { id: 'product-2', quantity: 1 }]
  try {
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    const goto = async path => {
      const response = await page.goto(`${base}${path}`, { waitUntil: 'domcontentloaded' })
      await page.waitForSelector('main h1')
      if (expectedAsset) { assert.equal(response.status(), 200); assert((await page.locator('script[type=module]').getAttribute('src')).includes(expectedAsset)) }
    }
    await goto('/')
    await page.evaluate(lines => { localStorage.clear(); sessionStorage.clear(); localStorage.setItem('garage-cart-v2', JSON.stringify(lines)) }, seed)
    await goto('/cart')
    const total = async () => Number((await page.getByTestId('order-total').innerText()).replace(/[^\d,]/g, '').replace(',', '.'))
    const checkTotal = async amount => { await page.waitForFunction(amount => Number(document.querySelector('[data-testid=order-total]')?.textContent.replace(/[^\d,]/g, '').replace(',', '.')) === amount, amount); assert.equal(await total(), amount) }
    const overflow = async () => { await page.evaluate(() => document.fonts.ready); assert(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth <= 1), 'Document overflow') }
    const screenshot = async name => { if (screenshotRoot) await page.screenshot({ path: `${screenshotRoot}/${name}-${width}.png`, fullPage: true }) }
    const apply = async code => { await page.getByLabel('Промокод', { exact: true }).fill(code); await page.getByRole('button', { name: 'Применить промокод', exact: true }).click() }
    assert.equal(await page.getByRole('dialog').count(), 0)
    assert(!(await page.locator('.cart-recipient').innerText()).includes('Алексей'))
    await checkTotal(46800)
    const lineAmount = async (index, testId) => Number((await page.getByTestId('cart-line').nth(index).getByTestId(testId).innerText()).replace(/[^\d,]/g, '').replace(',', '.'))
    assert.equal(await lineAmount(0, 'line-old-price'), 21168)
    assert.equal(await page.getByTestId('cart-line').nth(1).getByTestId('line-old-price').count(), 0)
    assert.equal(await page.locator('.line-accessories[open]').count(), 2)
    const summary = page.getByRole('complementary', { name: 'Итоги заказа' })
    const firstPanel = page.locator('.line-accessories').first()
    const firstRail = firstPanel.locator('.line-accessories__rail')
    assert.equal(await firstRail.locator('article').count(), 7)
    assert.equal(new Set(await firstRail.locator('article').evaluateAll(items => items.map(item => item.getAttribute('data-related-id')))).size, 7)
    await firstRail.evaluate(el => el.scrollIntoView({ block: 'center', inline: 'nearest', behavior: 'instant' }))
    await firstPanel.getByRole('button', { name: 'Следующие сопутствующие товары', exact: true }).waitFor({ state: 'visible' })
    if (width < 600) {
      const cdp = await context.newCDPSession(page)
      try {
        const swipe = async () => {
          const box = await firstRail.boundingBox()
          const start = box.x + box.width - 20, end = box.x + 20, y = box.y + box.height / 2
          await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: start, y }] })
          for (let step = 1; step <= 6; step++) {
            await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: start + (end - start) * step / 6, y }] })
            await page.evaluate(() => new Promise(resolve => requestAnimationFrame(resolve)))
          }
          await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
        }
        await swipe()
        await page.waitForFunction(el => el.scrollLeft > 0, await firstRail.elementHandle(), { timeout: 5000 })
        for (let attempt = 0; attempt < 12 && await firstRail.evaluate(el => el.scrollLeft < el.scrollWidth - el.clientWidth - 2); attempt++) await swipe()
      } finally { await cdp.detach() }
    } else {
      await firstPanel.getByRole('button', { name: 'Следующие сопутствующие товары', exact: true }).click()
      await page.waitForFunction(el => el.scrollLeft > 0, await firstRail.elementHandle(), { timeout: 5000 })
      await firstRail.focus(); await page.keyboard.press('ArrowRight')
      await firstRail.locator('article').last().scrollIntoViewIfNeeded()
    }
    assert(await firstRail.locator('article').last().evaluate(el => el.getBoundingClientRect().right <= el.parentElement.getBoundingClientRect().right + 2), 'Last recommendation is not reachable')
    await firstRail.evaluate(el => el.scrollTo({ left: 0, behavior: 'instant' }))
    await page.evaluate(() => scrollTo(0, 0))
    assert.equal(await summary.locator('.cart-tools').count(), 1)
    assert.equal(await page.locator('.cart-page>.cart-tools').count(), 0)
    await screenshot('before')
    await apply('')
    assert((await page.getByRole('alert').innerText()).includes('Введите промокод'))
    await apply('wrong')
    await checkTotal(46800)
    await screenshot('error')
    await apply(' 123 ')
    await checkTotal(42120)
    assert((await page.getByTestId('promo-discount').innerText()).includes('4 680') || (await page.getByTestId('promo-discount').innerText()).replace(/\s/g, '').includes('4680'))
    assert.equal(await page.getByTestId('line-old-price').count(), 2)
    assert.equal(await page.getByTestId('line-new-price').count(), 2)
    assert.equal(await lineAmount(0, 'line-old-price'), 21168)
    assert.equal(await lineAmount(0, 'line-new-price'), 17010)
    assert.equal(await lineAmount(1, 'line-old-price'), 27900)
    assert.equal(await lineAmount(1, 'line-new-price'), 25110)
    assert.equal(await summary.locator('del').count(), 0)
    assert.equal(await summary.getByRole('group', { name: 'Расшифровка скидок' }).count(), 1)
    assert.equal(await page.getByText('С промокодом −10%', { exact: true }).count(), 0)
    await overflow()
    await screenshot('applied')
    await apply('123')
    await checkTotal(42120)
    await page.getByTestId('cart-line').first().getByRole('button', { name: 'Увеличить количество' }).click()
    await checkTotal(59130)
    await page.getByTestId('cart-line').first().getByRole('button', { name: 'Уменьшить количество' }).click()
    await page.getByTestId('cart-line').nth(1).getByRole('checkbox').uncheck()
    await checkTotal(17010)
    await page.getByTestId('cart-line').first().getByRole('checkbox').uncheck()
    await checkTotal(0)
    await page.getByTestId('cart-line').first().getByRole('button', { name: 'Увеличить количество' }).click()
    await checkTotal(0)
    assert.equal(await page.getByTestId('promo-discount').count(), 0)
    await page.getByTestId('cart-line').first().getByRole('button', { name: 'Уменьшить количество' }).click()
    await page.getByRole('checkbox', { name: 'Выбрать все товары' }).check()
    await checkTotal(42120)
    await page.getByRole('button', { name: 'Удалить промокод' }).click()
    await checkTotal(46800)
    assert.equal(await lineAmount(0, 'line-new-price'), 18900)
    assert.equal(await lineAmount(1, 'line-new-price'), 27900)
    assert.equal(await page.getByTestId('cart-line').nth(1).getByTestId('line-old-price').count(), 0)
    assert((await page.getByRole('status').innerText()).includes('Промокод удалён'))
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('garage-checkout-v2')).promoCode ?? null), null)
    await screenshot('removed')
    await page.reload({ waitUntil: 'domcontentloaded' }); await checkTotal(46800)
    await apply('123')
    await page.reload({ waitUntil: 'domcontentloaded' })
    await checkTotal(42120)
    const login = page.getByRole('button', { name: 'Войти или зарегистрироваться', exact: true })
    await login.click()
    await page.getByRole('dialog', { name: 'Вход и регистрация' }).waitFor()
    await page.keyboard.press('Escape')
    await checkTotal(42120)
    const stock = page.getByRole('button', { name: /^Наличие в магазинах:/ }).first()
    await stock.click()
    assert((await page.getByRole('dialog').innerText()).includes('Наличие в этой точке уточняется'))
    await page.keyboard.press('Escape')
    assert(await stock.evaluate(el => el === document.activeElement))
    for (const name of ['Коммерческое предложение', 'Купить в кредит']) {
      const trigger = summary.getByRole('button', { name, exact: true })
      await trigger.click()
      const dialog = page.getByRole('dialog', { name, exact: true })
      await dialog.waitFor()
      assert((await dialog.innerText()).replace(/\s/g, '').includes('42120'))
      await page.keyboard.press('Shift+Tab')
      assert(await dialog.evaluate(el => el.contains(document.activeElement)))
      await overflow()
      await page.keyboard.press('Escape')
      assert(await trigger.evaluate(el => el === document.activeElement))
    }
    await page.getByRole('toolbar', {name: 'Действия с товарами'}).getByRole('button', { name: 'Поделиться корзиной', exact: true }).click()
    const shareURL = await page.getByLabel('Ссылка на корзину', { exact: true }).inputValue()
    const payload = JSON.parse(atob(new URL(shareURL).searchParams.get('shared')))
    assert.deepEqual(payload, seed)
    await page.evaluate(() => { Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async value => { window.__copiedCartLink = value } } }) })
    await page.getByRole('button', { name: 'Копировать ссылку', exact: true }).click()
    assert.equal(await page.evaluate(() => window.__copiedCartLink), shareURL)
    await page.keyboard.press('Escape')
    const receiver = await browser.newContext({ viewport: { width, height: 1000 } })
    try {
      const p = await receiver.newPage()
      await p.goto(shareURL, { waitUntil: 'domcontentloaded' })
      await p.getByRole('button', { name: 'Добавить в мою корзину' }).click()
      await p.getByTestId('cart-line').first().waitFor()
      assert.equal(await p.getByTestId('cart-line').count(), 2)
      assert.equal(await p.getByTestId('promo-discount').count(), 0)
    } finally { await receiver.close() }
    await goto('/product/product-3/')
    await goto('/cart')
    await page.getByRole('region', { name: 'Просмотренные товары' }).waitFor()
    assert.equal(await page.locator('.cart-viewed .product-teaser').count(), 1)
    await page.getByRole('link', { name: 'Перейти к оформлению', exact: true }).click()
    await checkTotal(42120)
    assert.equal(await page.getByTestId('checkout-submit').getAttribute('aria-disabled'), 'true')
    await page.getByRole('button', { name: 'Войти или зарегистрироваться', exact: true }).click()
    const auth = page.getByRole('dialog', { name: 'Вход и регистрация' })
    await auth.getByLabel('Номер телефона', { exact: true }).fill('+7 999 111-22-33')
    await auth.getByRole('button', { name: 'Получить код', exact: true }).click()
    await auth.getByLabel('Код подтверждения', { exact: true }).fill('1234')
    await auth.getByRole('button', { name: 'Войти', exact: true }).click()
    await auth.waitFor({ state: 'hidden' })
    await checkTotal(42120)
    await page.getByLabel('Город самовывоза').selectOption('Ярославль')
    await page.getByRole('radio', { name: /Демо-магазин/ }).check()
    await screenshot('checkout')
    await page.getByTestId('checkout-submit').click()
    await page.getByRole('heading', { name: 'Заказ принят', exact: true }).waitFor()
    await checkTotal(42120)
    await screenshot('success')
    await goto('/cart')
    await page.getByRole('button', { name: 'Удалить промокод' }).click()
    await checkTotal(46800)
    await goto('/checkout/success/')
    await checkTotal(42120)
    await page.evaluate(() => { localStorage.setItem('garage-cart-v2', JSON.stringify([1,2,3,4,5].map(id => ({ id: `product-${id}`, quantity: 1 })))); localStorage.removeItem('garage-checkout-v2') })
    await goto('/cart')
    assert.equal(await page.locator('.line-accessories[open]').count(), 1)
    for (let index = 0; index < 5; index++) {
      const panel = page.locator('.line-accessories').nth(index)
      if (index) await panel.locator('summary').click()
      const rail = panel.locator('.line-accessories__rail')
      assert.equal(await rail.locator('article').count(), [7,5,6,7,8][index])
      const ids = await rail.locator('article').evaluateAll(els => els.map(el => el.getAttribute('data-related-id')))
      assert.equal(new Set(ids).size, ids.length)
      if (index) {
        await panel.getByRole('button', { name: 'Следующие сопутствующие товары', exact: true }).click()
        await page.waitForFunction(el => el.scrollLeft > 0, await rail.elementHandle())
        await rail.focus()
        await page.keyboard.press('End')
        await rail.evaluate(el => { el.scrollLeft = el.scrollWidth })
        await rail.locator('article').last().scrollIntoViewIfNeeded()
      } else assert((await rail.locator('article').first().boundingBox()).width <= 305)
      await overflow()
    }
    await screenshot('five-lines')
    await page.getByTestId('cart-line').nth(4).getByRole('button', { name: /^Наличие в магазинах:/ }).click()
    assert((await page.getByRole('dialog').innerText()).includes('Нет в наличии'))
    await page.keyboard.press('Escape')
    await page.getByTestId('cart-line').nth(4).getByRole('button', { name: 'Удалить товар', exact: true }).click()
    await checkTotal(129600)
    await page.evaluate(() => { localStorage.setItem('garage-cart-v2', JSON.stringify([{ id: 'compressor-8', quantity: 1 }])); localStorage.removeItem('garage-checkout-v2') })
    await goto('/cart')
    await apply('123')
    assert.equal(await page.getByTestId('order-total').innerText(), 'Уточняется')
    assert.equal(await page.getByTestId('line-new-price').count(), 0)
    assert.equal(await page.getByTestId('promo-discount').count(), 0)
    await page.evaluate(() => localStorage.setItem('garage-cart-v2', '[]'))
    await goto('/cart')
    assert.equal(await page.getByTestId('cart-line').count(), 0)
    assert.equal(await page.getByTestId('promo-discount').count(), 0)
    await overflow()
    assert.deepEqual(errors, [])
    return { width, promo: true, snapshot: true, share: true, history: true, rails: [7,5,6,7,8], quote: true, guestGate: true, errors }
  } finally { await context.close() }
}
