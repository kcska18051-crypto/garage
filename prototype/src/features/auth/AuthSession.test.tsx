import { render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { MemoryRouter } from 'react-router-dom'
import { App } from '../../app/App'

const open = (path='/profile/data') => render(<MemoryRouter initialEntries={[path]}><App/></MemoryRouter>)

describe('account session consistency', () => {
  beforeEach(() => { localStorage.clear(); sessionStorage.clear() })
  it('does not expose personal account data through a guest direct URL', () => {
    open()
    expect(screen.queryByText('Алексей Смирнов')).not.toBeInTheDocument()
    expect(screen.queryByText('Телефон подтверждён')).not.toBeInTheDocument()
    expect(screen.queryByLabelText('Имя')).not.toBeInTheDocument()
    expect(screen.getByRole('region', { name:'Вход в личный кабинет' })).toHaveTextContent('Войдите')
  })
  it('keeps checkout intent and entered choices through an explicit login', async () => {
    const user=userEvent.setup(); open('/checkout/review?from=cart#checkout-delivery')
    expect(screen.queryByLabelText('Подтверждённый телефон')).not.toBeInTheDocument()
    await user.selectOptions(screen.getByLabelText('Город самовывоза'),'Вологда')
    await user.click(screen.getByRole('radio',{name:/Демо-пункт выдачи/}))
    await user.type(screen.getByLabelText('Комментарий к заказу'),'Сохранить намерение')
    await user.click(screen.getByLabelText('СБП'))
    await user.click(screen.getByRole('button',{name:'Войти или зарегистрироваться'}))
    const dialog=screen.getByRole('dialog',{name:'Вход и регистрация'})
    await user.click(within(dialog).getByRole('button',{name:'По паролю'}))
    await user.click(within(dialog).getByRole('button',{name:'Войти'}))
    expect(screen.getByRole('heading',{name:'Оформление заказа'})).toBeInTheDocument()
    expect(screen.getByLabelText('Комментарий к заказу')).toHaveValue('Сохранить намерение')
    expect(screen.getByRole('radio',{name:/Демо-пункт выдачи/})).toBeChecked()
    expect(screen.getByLabelText('СБП')).toBeChecked()
    expect(screen.getByLabelText('Подтверждённый телефон')).toHaveAttribute('readonly')
  })
  it('does not interpret arbitrary stored values as successful authentication', () => {
    sessionStorage.setItem('garage-auth-demo-session-v1','false')
    open('/profile/orders')
    expect(screen.getByRole('region',{name:'Вход в личный кабинет'})).toBeInTheDocument()
    expect(screen.queryByText('Алексей Смирнов')).not.toBeInTheDocument()
  })
  it('persists an explicit demo login, really logs out and does not reset the cart or favorites', async () => {
    const user=userEvent.setup()
    localStorage.setItem('garage-cart-v2',JSON.stringify([{id:'product-1',quantity:2}]))
    let view=open('/profile/favorites')
    await user.click(within(screen.getByTestId('profile-product-product-1')).getByRole('button',{name:'Удалить из избранного'}))
    await user.click(screen.getByRole('navigation',{name:'Разделы личного кабинета'}).querySelector('a[href="/profile/data"]')!)
    const guest=screen.getByRole('region',{name:'Вход в личный кабинет'})
    await user.click(within(guest).getByRole('button',{name:'Войти / зарегистрироваться'}))
    const dialog=screen.getByRole('dialog',{name:'Вход и регистрация'})
    await user.click(within(dialog).getByRole('button',{name:'По паролю'}))
    expect(dialog).toHaveTextContent('Демонстрационный режим')
    await user.click(within(dialog).getByRole('button',{name:'Войти'}))
    expect(screen.getByLabelText('Имя')).toHaveValue('Алексей')
    expect(screen.getByRole('button',{name:'Выйти'})).toBeInTheDocument()
    const cart=localStorage.getItem('garage-cart-v2'), favorites=localStorage.getItem('garage-favorites-v1')
    view.unmount(); view=open()
    expect(screen.getByRole('button',{name:'Выйти'})).toBeInTheDocument()
    await user.click(screen.getByRole('button',{name:'Выйти'}))
    expect(screen.queryByLabelText('Имя')).not.toBeInTheDocument()
    expect(screen.queryByText('Алексей Смирнов')).not.toBeInTheDocument()
    expect(localStorage.getItem('garage-cart-v2')).toBe(cart)
    expect(localStorage.getItem('garage-favorites-v1')).toBe(favorites)
    view.unmount(); open()
    expect(screen.getByRole('region',{name:'Вход в личный кабинет'})).toBeInTheDocument()
    expect(screen.queryByRole('button',{name:'Выйти'})).not.toBeInTheDocument()
    expect(screen.getAllByRole('button',{name:'Профиль'}).length).toBeGreaterThan(0)
  })
})
