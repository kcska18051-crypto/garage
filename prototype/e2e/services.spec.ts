import {expect,test,type Page} from '@playwright/test'

const repairBase='/services/service-center/compressor-repair'
const routes=['/services','/services/service-center',repairBase,...['screw','piston','diesel'].map(id=>`${repairBase}/${id}`),'/services/paint-matching','/services/rental',...['hydraulic-jack','tool-set','piston-compressor'].map(id=>`/services/rental/${id}`)]
async function contacts(page:Page) {
  await page.getByLabel('Ваше имя',{exact:true}).fill('Демонстрация')
  await page.getByLabel('Телефон',{exact:true}).fill('+7 (999) 123-45-67')
}
for(const width of [360,390,1024,1440,1920,2560]) test(`services all routes responsive at ${width}`,async({page})=>{
  test.setTimeout(90000)
  await page.setViewportSize({width,height:900})
  for(const route of routes) {
    await page.goto(route)
    await expect(page.locator('main h1')).toBeVisible()
    await expect(page.locator('.services-heading')).toContainText('Демонстрационное')
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),route).toBe(true)
    for(const image of await page.locator('.services-art').all()) expect((await image.boundingBox())!.height).toBeLessThanOrEqual(200)
  }
  if([390,1440,1920].includes(width)) {
    await page.goto('/services');await page.screenshot({path:`test-results/services-${width}.png`,fullPage:true})
    await page.goto('/services/rental/hydraulic-jack');await page.screenshot({path:`test-results/rental-${width}.png`,fullPage:true})
    await page.getByRole('main').getByRole('button',{name:'Арендовать',exact:true}).click()
    await page.screenshot({path:`test-results/rental-form-${width}.png`,fullPage:true})
  }
})
