import {render,screen,within,waitFor} from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import {MemoryRouter} from 'react-router-dom'
import {App} from '../../app/App'
import {seedDemoSession} from '../../test/auth'

const open=(path='/services/service-center/compressor-repair/screw')=>render(<MemoryRouter initialEntries={[path]}><App/></MemoryRouter>)
async function repair(user:ReturnType<typeof userEvent.setup>){
  await user.click(screen.getByRole('button',{name:'Оставить заявку'}))
  await user.type(screen.getByLabelText('Ваше имя'),'Тестовый клиент')
  await user.type(screen.getByLabelText('Телефон'),'+7 999 123-45-67')
  await user.type(screen.getByLabelText('Модель оборудования'),'Приватная модель')
  await user.type(screen.getByLabelText('Описание неисправности'),'Не включается')
  await user.click(screen.getByRole('button',{name:'Отправить заявку'}))
}
beforeEach(()=>{localStorage.clear();sessionStorage.clear()})
it('uses one saved record for success, exact account detail and the list after reload',async()=>{
  seedDemoSession();const user=userEvent.setup();const view=open();await repair(user)
  await user.click(screen.getByRole('button',{name:'Посмотреть заявку в личном кабинете'}))
  expect(screen.getByRole('heading',{level:1,name:/Заявка № DEMO-SR-/})).toBeInTheDocument()
  expect(screen.getByText('Приватная модель')).toBeInTheDocument()
  const record=JSON.parse(localStorage.getItem('garage-service-requests-v1')!).find((r:{seed:boolean})=>!r.seed)
  view.unmount();open(`/profile/services/request/?id=${record.id}`)
  expect(screen.getByText('Приватная модель')).toBeInTheDocument()
  await user.click(screen.getByRole('link',{name:'Все заявки на услуги'}))
  expect(screen.getByText(new RegExp(record.number))).toBeInTheDocument()
  await user.click(screen.getByRole('navigation',{name:'Разделы личного кабинета'}).querySelector('a[href="/profile"]')!)
  expect(screen.getByRole('region',{name:'Сводка'}).querySelector('a[href="/profile/services"]')).toHaveTextContent('4')
})
it('shows the current identity phone and does not label a password demo as code confirmed',()=>{
  seedDemoSession();sessionStorage.setItem('garage-auth-demo-identity-v1',JSON.stringify({phone:'79991234567',phoneConfirmed:true}))
  const view=open('/profile/data')
  expect(screen.getByLabelText('Телефон')).toHaveValue('+79991234567')
  expect(screen.getByText('Телефон подтверждён в деморежиме')).toBeInTheDocument()
  view.unmount();sessionStorage.removeItem('garage-auth-demo-identity-v1');open('/profile/data')
  expect(screen.getByText('Телефон не подтверждён кодом')).toBeInTheDocument()
})
it('shows zero open requests for an identity without any owned history',()=>{
  seedDemoSession();sessionStorage.setItem('garage-auth-demo-identity-v1',JSON.stringify({phone:'79991112233',phoneConfirmed:true}))
  open('/profile')
  expect(screen.getByRole('region',{name:'Сводка'}).querySelector('a[href="/profile/services"]')).toHaveTextContent('0')
})
it('keeps a guest request private for another phone then opens it after matching confirmation',async()=>{
  const user=userEvent.setup();open();await repair(user)
  await user.click(screen.getByRole('button',{name:'Посмотреть заявку в личном кабинете'}))
  let dialog=screen.getByRole('dialog',{name:'Вход и регистрация'})
  expect(within(dialog).queryByRole('button',{name:'По паролю'})).not.toBeInTheDocument()
  await user.type(within(dialog).getByLabelText('Номер телефона'),'+7 900 111-22-33')
  await user.click(within(dialog).getByRole('button',{name:'Получить код'}))
  await user.type(within(dialog).getByLabelText('Код подтверждения'),'1234')
  await user.click(within(dialog).getByRole('button',{name:'Войти'}))
  expect(screen.queryByText('Приватная модель')).not.toBeInTheDocument()
  expect(screen.getByRole('heading',{name:'Заявка недоступна'})).toBeInTheDocument()
  await user.click(screen.getByRole('button',{name:'Подтвердить телефон заявки'}))
  dialog=screen.getByRole('dialog',{name:'Вход и регистрация'})
  await user.type(within(dialog).getByLabelText('Номер телефона'),'+7 999 123-45-67')
  await user.click(within(dialog).getByRole('button',{name:'Получить код'}))
  await user.type(within(dialog).getByLabelText('Код подтверждения'),'1234')
  await user.click(within(dialog).getByRole('button',{name:'Войти'}))
  await waitFor(()=>expect(screen.getByText('Приватная модель')).toBeInTheDocument())
  await user.click(screen.getByRole('button',{name:'Выйти'}))
  expect(screen.queryByText('Приватная модель')).not.toBeInTheDocument()
})
