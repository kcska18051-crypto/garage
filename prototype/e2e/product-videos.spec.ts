import {test,expect} from '@playwright/test'
test.beforeEach(async({page})=>{await page.route('**/garage/style-check/**',route=>route.continue({url:route.request().url().replace('/garage/style-check/','/style-check/')}))})
for(const width of [320,1440])test(`compact video previews at ${width}`,async({page})=>{
 await page.setViewportSize({width,height:900})
 await page.addInitScript(()=>{localStorage.setItem('garage-region-v1','Ярославль');localStorage.setItem('garage-cookie-preference',JSON.stringify({version:2,choice:'necessary'}))})
 await page.goto('/product/remeza-vk-10-gr-0001#video')
 const section=page.getByRole('region',{name:'Видео'})
 await expect(section.getByRole('button',{name:/Предпросмотр видео:/})).toHaveCount(4)
 expect(await section.locator('.product-videos__grid').evaluate(e=>getComputedStyle(e).gridTemplateColumns.split(' ').length)).toBe(width<901?2:4)
 await section.getByRole('button',{name:'Показать ещё 4'}).click()
 await expect(section.getByRole('button',{name:/Предпросмотр видео:/})).toHaveCount(8)
 await section.screenshot({path:`C:/Users/Admin/garage-audit/videos-${width}.png`})
 const trigger=section.getByRole('button',{name:'Предпросмотр видео: Диагностика оборудования'})
 await trigger.click()
 const dialog=page.getByRole('dialog',{name:'Диагностика оборудования'})
 await expect(dialog).toBeVisible();await expect(dialog).toContainText('Видеоролик пока не подключён')
 await page.keyboard.press('Tab');await expect(dialog.getByRole('button',{name:'Закрыть диалог'})).toBeFocused()
 await page.keyboard.press('Escape');await expect(dialog).toHaveCount(0);await expect(trigger).toBeFocused()
 await page.emulateMedia({reducedMotion:'reduce'})
 await trigger.click();await dialog.getByRole('button',{name:'Закрыть диалог'}).click();await expect(dialog).toHaveCount(0)
 await section.getByRole('button',{name:'Свернуть'}).click()
 await expect(section.getByRole('button',{name:/Предпросмотр видео:/})).toHaveCount(4)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
