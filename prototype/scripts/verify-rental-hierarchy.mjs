import assert from 'node:assert/strict'

export async function verifyRentalHierarchy(browser,{base,width,expectedAsset,screenshotRoot}) {
  const context=await browser.newContext({viewport:{width,height:1000}})
  try {
    const page=await context.newPage(), errors=[]
    page.on('pageerror',error=>errors.push(error.message))
    const goto=async path=>{
      const response=await page.goto(`${base}${path}`,{waitUntil:'domcontentloaded'})
      assert.equal(response.status(),200)
      await page.locator('main h1').waitFor()
      if(expectedAsset) assert((await page.locator('script[type=module]').getAttribute('src')).includes(expectedAsset))
    }
    const noOverflow=async()=>{
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Document overflow')
      for(const el of await page.locator('[role=dialog],dialog').all()) if(await el.isVisible()) assert(await el.evaluate(el=>el.scrollWidth<=el.clientWidth+1),'Dialog overflow')
    }
    const shot=async name=>{if(screenshotRoot)await page.screenshot({path:`${screenshotRoot}/${name}-${width}.png`,fullPage:!(await page.getByRole('dialog').count())})}
    await goto('/services/rental/')
    assert.equal(await page.locator('main h1').innerText(),'Аренда оборудования и инструмента')
    assert.equal(await page.locator('.services-grid article').count(),2)
    assert.equal(await page.getByRole('main').getByRole('button',{name:/Арендовать/}).count(),0)
    await noOverflow();await shot('rental-root')
    await page.getByRole('main').getByRole('link',{name:'Аренда инструмента',exact:true}).click()
    assert.equal(await page.locator('main h1').innerText(),'Инструмент в аренду')
    assert.deepEqual(await page.locator('[data-rental-id]').evaluateAll(els=>els.map(el=>el.dataset.rentalId)),['hydraulic-jack','tool-set'])
    assert.equal(await page.getByRole('button',{name:/Арендовать/}).count(),0)
    await noOverflow()
    await page.locator('a[href$="/services/rental/hydraulic-jack"]').first().click()
    assert((await page.getByRole('navigation',{name:'Хлебные крошки'}).innerText()).includes('Инструмент в аренду'))
    await page.getByRole('button',{name:'Арендовать',exact:true}).click()
    await page.getByRole('dialog',{name:'Заявка на аренду'}).waitFor()
    await page.keyboard.press('Escape')
    await goto('/product/remeza-vk-10-gr-0001/')
    await page.evaluate(()=>localStorage.setItem('garage-cart-v2',JSON.stringify([{id:'product-2',quantity:2}])))
    await page.reload({waitUntil:'domcontentloaded'})
    const before=await page.evaluate(()=>localStorage.getItem('garage-cart-v2'))
    const trigger=page.getByRole('button',{name:'Можно взять в аренду'})
    await trigger.focus();await page.keyboard.press('Enter')
    const info=page.getByRole('dialog',{name:'Можно взять в аренду'})
    await info.waitFor()
    assert.equal(await info.getByLabel('Дата начала').count(),0)
    assert.equal(await info.getByRole('link',{name:'Компрессоры в аренду'}).getAttribute('href'),'/garage/services/rental/compressors')
    await noOverflow();await shot('rental-message')
    await page.keyboard.press('Shift+Tab')
    assert(await info.getByRole('link').evaluate(el=>el===document.activeElement),'Information dialog focus trap')
    await page.keyboard.press('Tab')
    assert(await info.getByRole('button',{name:'Закрыть диалог'}).evaluate(el=>el===document.activeElement))
    await page.keyboard.press('Escape')
    assert(await trigger.evaluate(el=>el===document.activeElement),'Information dialog restores focus')
    await trigger.click();await info.getByRole('link',{name:'Компрессоры в аренду'}).click()
    assert.equal(await page.locator('main h1').innerText(),'Компрессоры в аренду')
    assert.deepEqual(await page.locator('[data-rental-id]').evaluateAll(els=>els.map(el=>el.dataset.rentalId)),['piston-compressor','screw-compressor'])
    const card=page.locator('[data-rental-id="screw-compressor"]')
    assert((await card.innerText()).includes('380 В'));assert((await card.innerText()).includes('7,5 кВт'))
    await noOverflow();await shot('rental-compressors')
    const rent=card.getByRole('button',{name:/Арендовать/})
    await rent.click()
    const form=page.getByRole('dialog',{name:'Заявка на аренду'})
    assert.equal(await form.locator('.service-request-selection').innerText(),'Винтовой компрессор Remeza ВК 10-8 с ременным приводом')
    await page.keyboard.press('Escape');assert(await rent.evaluate(el=>el===document.activeElement))
    await rent.click();await noOverflow();await shot('rental-form')
    await form.getByRole('button',{name:'Отправить заявку'}).click()
    assert.equal(await form.getByLabel('Ваше имя').getAttribute('aria-invalid'),'true')
    await form.getByLabel('Ваше имя').fill('Демо аренда')
    await form.getByLabel('Телефон',{exact:true}).fill('+79991234567')
    await form.getByLabel('Дата начала',{exact:true}).fill('2099-01-02')
    await form.getByLabel('Дата окончания',{exact:true}).fill('2099-01-01')
    await form.getByLabel('Количество',{exact:true}).fill('1.5')
    await form.getByRole('button',{name:'Отправить заявку'}).click()
    assert.equal(await form.getByLabel('Дата окончания',{exact:true}).getAttribute('aria-invalid'),'true')
    assert.equal(await form.getByLabel('Количество',{exact:true}).getAttribute('aria-invalid'),'true')
    await form.getByLabel('Дата окончания',{exact:true}).fill('2099-01-03')
    await form.getByLabel('Количество',{exact:true}).fill('2')
    await form.getByLabel('Комментарий').fill('Проверка аренды')
    await form.getByRole('button',{name:'Отправить заявку'}).click()
    await page.locator('.service-request-number').waitFor()
    const record=await page.evaluate(()=>JSON.parse(localStorage.getItem('garage-service-requests-v1')).find(r=>!r.seed))
    assert.equal(record.kind,'rental');assert.equal(record.itemId,'screw-compressor');assert.equal(record.status,'Ожидает подтверждения')
    assert.equal(record.fields.quantity,'2');assert.equal(record.fields.start,'2099-01-02');assert.equal(record.fields.comment,'Проверка аренды')
    assert.equal(await page.evaluate(()=>localStorage.getItem('garage-cart-v2')),before)
    await page.getByRole('button',{name:'Посмотреть заявку в личном кабинете'}).click()
    const auth=page.getByRole('dialog',{name:'Вход и регистрация'})
    await auth.getByLabel('Номер телефона').fill('+79991234567')
    await auth.getByRole('button',{name:'Получить код'}).click()
    await auth.getByLabel('Код подтверждения').fill('1234')
    await auth.getByRole('button',{name:'Войти',exact:true}).click()
    await page.getByRole('heading',{name:`Заявка № ${record.number}`,exact:true}).waitFor()
    assert.equal(new URL(page.url()).searchParams.get('id'),record.id)
    await page.reload({waitUntil:'domcontentloaded'})
    await page.getByRole('heading',{name:`Заявка № ${record.number}`,exact:true}).waitFor()
    assert((await page.locator('main').innerText()).includes('Ожидает подтверждения'))
    await noOverflow();await shot('rental-account')
    for(const [id,heading] of [['hydraulic-jack','Инструмент в аренду'],['tool-set','Инструмент в аренду'],['piston-compressor','Компрессоры в аренду'],['screw-compressor','Компрессоры в аренду']]){
      await goto(`/services/rental/${id}/`)
      assert((await page.getByRole('navigation',{name:'Хлебные крошки'}).innerText()).includes(heading))
      await page.getByRole('button',{name:'Арендовать',exact:true}).click();await noOverflow();await page.keyboard.press('Escape')
    }
    for(const id of ['product-3','remeza-vk-10-220-55']){
      await goto(`/product/${id}/`)
      assert.equal(await page.getByRole('button',{name:'Можно взять в аренду'}).count(),0)
    }
    assert.equal(await page.evaluate(()=>localStorage.getItem('garage-cart-v2')),before)
    assert.deepEqual(errors,[])
    return {width,status:'PASS',requestId:record.id,cart:'unchanged',legacyDetails:4}
  } finally {await context.close()}
}
