import { expect, test } from '@playwright/test'

for (const width of [360,390,1440,1920]) {
  test.describe(`pickup ${width}`, () => {
    test.use({ viewport: { width, height: 900 }, hasTouch: width < 600 })
    test('radio selection, local details, keyboard, map and checkout preservation', async ({ page }) => {
      await page.route('https://tile.openstreetmap.org/**', route => route.abort())
      await page.goto('/checkout/review')
      const summary = page.getByRole('complementary', { name: 'Итоги заказа' })
      const radio = page.getByRole('radio', { name: /Демо-магазин/ })
      const trigger = page.getByRole('button', { name: 'Фото и как добраться: Демо-магазин' })
      await expect(radio).not.toBeChecked()
      await expect(page.getByText('Выбран', { exact: true })).toHaveCount(0)
      await expect(summary).toContainText('Пункт не выбран')
      await page.getByLabel('Заберёт другой человек').check()
      await page.getByLabel('Имя получателя', { exact: true }).fill('Анна')
      await page.getByLabel('Фамилия получателя').fill('Демо')
      await page.getByLabel('Телефон получателя').fill('+79001234567')
      await page.getByLabel('СБП', { exact: true }).check()
      await page.getByLabel('Комментарий к заказу').fill('Не звонить утром')
      await trigger.click()
      const dialog = page.getByRole('dialog', { name: /Демо-магазин/ })
      const close = dialog.getByRole('button', { name: 'Закрыть информацию о пункте' })
      await expect(close).toBeFocused()
      await expect(dialog).toContainText('Демонстрационные данные')
      await expect(dialog.getByRole('img', { name: 'Место для фотографии: Фасад' })).toBeVisible()
      await expect(dialog.getByRole('link', { name: /Построить маршрут/ })).toHaveAttribute('target', '_blank')
      await expect(dialog.locator('.coordinate-map image')).toHaveCount(0)
      await page.screenshot({ path: `artifacts/pickup-panel-${width}.png` })
      await page.keyboard.press('Shift+Tab')
      expect(await dialog.evaluate(el => el.contains(document.activeElement))).toBe(true)
      await page.keyboard.press('Tab')
      await expect(close).toBeFocused()
      await expect(page).toHaveURL(/checkout\/review/)
      expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
      await page.keyboard.press('Escape')
      await expect(dialog).toHaveCount(0)
      await expect(trigger).toBeFocused()
      await expect(radio).not.toBeChecked()
      // A keyboard user can select the card without an extra action button.
      if (width < 600) await page.getByText('Демонстрационный адрес, дом 1', { exact: true }).tap()
      else { await radio.focus(); await page.keyboard.press('Space') }
      await expect(radio).toBeChecked()
      await expect(page.getByText('Выбран', { exact: true })).toBeVisible()
      await expect(summary).toContainText('Демо-магазин')
      await expect(page.getByRole('button', { name: 'На карте: Демо-магазин' })).toHaveAttribute('aria-pressed','true')
      await trigger.click(); await close.click()
      await expect(trigger).toBeFocused()
      await expect(radio).toBeChecked()
      await expect(page.getByLabel('Имя получателя', { exact: true })).toHaveValue('Анна')
      await expect(page.getByLabel('СБП', { exact: true })).toBeChecked()
      await expect(page.getByLabel('Комментарий к заказу')).toHaveValue('Не звонить утром')
      await page.getByLabel('Город самовывоза').selectOption('Вологда')
      const vologda = page.getByRole('radio', { name: /Демо-пункт выдачи/ })
      await expect(vologda).not.toBeChecked()
      await expect(summary).toContainText('Пункт не выбран')
      const marker = page.getByRole('button', { name: 'На карте: Демо-пункт выдачи' })
      await marker.focus(); await page.keyboard.press('Enter')
      await expect(vologda).toBeChecked()
      await expect(marker).toHaveAttribute('aria-pressed','true')
      await expect(marker).toHaveAttribute('transform','translate(384 192)')
      await expect(summary).toContainText('Вологда — Демо-пункт выдачи')
      await page.reload()
      await expect(vologda).toBeChecked()
      await expect(page.getByLabel('Комментарий к заказу')).toHaveValue('Не звонить утром')
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      const submit = page.getByTestId('checkout-submit')
      await submit.scrollIntoViewIfNeeded()
      await expect(submit).toBeVisible()
      await expect(submit).toHaveAttribute('aria-disabled','false')
      const unblocked = await submit.evaluate(el => { const r=el.getBoundingClientRect(); const top=document.elementFromPoint(r.x+r.width/2,r.y+r.height/2); return top===el || el.contains(top) })
      expect(unblocked).toBe(true)
      await page.screenshot({ path: `artifacts/pickup-checkout-${width}.png` })
    })
  })
}
