async function login(page:Page,phone:string){
  const auth=page.getByRole('dialog',{name:'Вход и регистрация'})
  await expect(auth.getByRole('button',{name:'По паролю'})).toHaveCount(0)
  await auth.getByLabel('Номер телефона').fill(phone)
  await auth.getByRole('button',{name:'Получить код'}).click()
  await auth.getByLabel('Код подтверждения').fill('1234')
  await auth.getByRole('button',{name:'Войти',exact:true}).click()
}
const cases=[['repair','/services/service-center/compressor-repair/screw/','Оставить заявку','Модель для проверки'],['paint','/services/paint-matching/automotive/','Оставить заявку','Демонстрационный автомобиль'],['rental','/services/rental/hydraulic-jack/','Арендовать','Локальная аренда-пример']] as const
for(const width of [360,390,1440,1920])test(`three forms share stable account records at ${width}`,async({page})=>{
  test.setTimeout(90000)
  await page.setViewportSize({width,height:900})
  await page.addInitScript(()=>{
    sessionStorage.setItem('garage-auth-demo-session-v1','active')
    sessionStorage.setItem('garage-auth-demo-identity-v1',JSON.stringify({phone:'79991234567',phoneConfirmed:true}))
  })
  for(const [kind,route,button,value] of cases){
    await page.goto(route)
    const cart=await page.evaluate(()=>localStorage.getItem('garage-cart-v2'))
    await page.getByRole('button',{name:button,exact:true}).click()
    await fill(page,kind)
    await page.getByRole('button',{name:'Отправить заявку'}).click()
    const dialog=page.getByRole('dialog')
    const number=(await dialog.locator('.service-request-number').innerText()).replace('Номер: ','')
    await expect(dialog).toContainText(kind==='rental'?'Ожидает подтверждения':'Новая заявка')
    if(kind==='repair')await expect(dialog).toContainText('сам файл не сохранён')
    await dialog.getByRole('button',{name:'Посмотреть заявку в личном кабинете'}).click()
    await expect(page).toHaveURL(/\/profile\/services\/request\/\?id=sr-/)
    const href=page.url()
    await expect(page.locator('main h1')).toHaveText(`Заявка № ${number}`)
    await expect(page.locator('main')).toContainText(value)
    if(kind==='repair')await expect(page.locator('main')).toContainText('Сам файл не сохранён')
    await page.reload()
    await expect(page.locator('main')).toContainText(value)
    await expect(page.locator('main h1')).toHaveText(`Заявка № ${number}`)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    if(kind==='rental')await page.screenshot({path:`test-results/services-account-${width}.png`,fullPage:true})
    await page.getByRole('link',{name:'Все заявки на услуги',exact:true}).click()
    const article=page.locator('.profile-request').filter({hasText:number})
    await expect(article).toHaveCount(1)
    await article.getByRole('link',{name:'Подробнее'}).click()
    await expect(page).toHaveURL(href)
    expect(await page.evaluate(()=>localStorage.getItem('garage-cart-v2'))).toBe(cart)
  }
})
test('guest mismatch, matching phone, exact intent, reload and logout privacy',async({page})=>{
  await page.goto('/services/service-center/compressor-repair/screw/')
  await page.getByRole('button',{name:'Оставить заявку'}).click();await fill(page,'repair')
  await page.getByRole('button',{name:'Отправить заявку'}).click()
  await page.getByRole('button',{name:'Посмотреть заявку в личном кабинете'}).click()
  const href=page.url()
  await login(page,'+7 900 111-22-33')
  await expect(page.locator('main h1')).toHaveText('Заявка недоступна')
  await expect(page.locator('main')).not.toContainText('Модель для проверки')
  await page.getByRole('button',{name:'Подтвердить телефон заявки'}).click()
  await login(page,'8 (999) 123-45-67')
  await expect(page).toHaveURL(href)
  await expect(page.locator('main')).toContainText('Модель для проверки')
  await page.reload();await expect(page.locator('main')).toContainText('Модель для проверки')
  await page.getByRole('button',{name:'Выйти',exact:true}).click()
  await expect(page.locator('main')).not.toContainText('Модель для проверки')
  await page.reload();await expect(page.locator('main')).not.toContainText('Модель для проверки')
  await page.getByRole('region',{name:'Вход в личный кабинет'}).getByRole('button',{name:'Войти / зарегистрироваться'}).click()
  await login(page,'+7 900 111-22-33')
  await expect(page.locator('main h1')).toHaveText('Заявка недоступна')
  await page.goto('/profile/services/request/?id=not-a-real-request')
  await expect(page.locator('main h1')).toHaveText('Заявка недоступна')
})
test('quota keeps form inputs and a double submit creates just one record',async({page})=>{
  await page.goto('/services/paint-matching/automotive/')
  await page.getByRole('button',{name:'Оставить заявку'}).click();await fill(page,'paint')
  await page.evaluate(()=>{const original=Storage.prototype.setItem;Object.assign(window,{restoreServiceStorage:()=>Storage.prototype.setItem=original});Storage.prototype.setItem=function(k,v){if(k==='garage-service-requests-v1')throw new DOMException('Quota','QuotaExceededError');return original.call(this,k,v)}})
  await page.getByRole('button',{name:'Отправить заявку'}).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('Не удалось сохранить')
  await expect(page.getByLabel('Автомобиль',{exact:true})).toHaveValue('Демонстрационный автомобиль')
  await page.evaluate(()=>{(window as unknown as {restoreServiceStorage():void}).restoreServiceStorage()})
  await page.locator('.service-request-dialog form').evaluate(form=>{form.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true}));form.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true}))})
  await expect(page.getByRole('button',{name:'Посмотреть заявку в личном кабинете'})).toBeVisible()
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('garage-service-requests-v1')!).filter((r:{seed:boolean})=>!r.seed).length)).toBe(1)
})
