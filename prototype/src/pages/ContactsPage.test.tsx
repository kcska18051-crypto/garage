import { render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { MemoryRouter } from 'react-router-dom'
import { App } from '../app/App'
import { contactPoints } from '../data/contactsData'

const open = () => render(<MemoryRouter initialEntries={['/contacts']}><App /></MemoryRouter>)

describe('contacts page', () => {
  it('uses three visible city tabs with keyboard selection instead of select or duplicate city badge', async () => {
    const user = userEvent.setup(); open()
    const tabs = within(screen.getByRole('tablist', { name: 'Город контактов' })).getAllByRole('tab')
    expect(tabs.map(tab => tab.textContent)).toEqual(['Ярославль','Вологда','Череповец'])
    expect(tabs[0]).toHaveAttribute('aria-selected','true')
    expect(screen.queryByRole('combobox')).not.toBeInTheDocument()
    expect(screen.queryByText(/Город сайта:/)).not.toBeInTheDocument()
    tabs[0].focus(); await user.keyboard('{ArrowRight}')
    expect(tabs[1]).toHaveFocus()
    expect(tabs[1]).toHaveAttribute('aria-selected','true')
    expect(screen.getByRole('link', { name: /Открыть страницу: Демо-пункт выдачи/ })).toHaveAttribute('href', expect.stringContaining('/contacts/pickup'))
    await user.keyboard('{End}')
    expect(tabs[2]).toHaveAttribute('aria-selected','true')
    await user.keyboard('{Home}')
    expect(tabs[0]).toHaveAttribute('aria-selected','true')
  })
  it('shows demo contacts, points and a schematic map', () => {
    open()
    expect(screen.getByRole('heading', { level: 1, name: 'Контакты' })).toBeInTheDocument()
    expect(screen.getByText(/Контактные данные на странице демонстрационные/i)).toBeInTheDocument()
    expect(screen.getAllByTestId('contact-point')).toHaveLength(1)
    expect(screen.getByRole('img', { name: 'Карта пунктов получения' })).toBeInTheDocument()
    expect(screen.getByText('contact@example.com')).toBeInTheDocument()
    expect(screen.queryByText(/маршрут построен/i)).not.toBeInTheDocument()
  })

  it('synchronizes city, header, filtered points and map', async () => {
    const user = userEvent.setup()
    open()
    expect(screen.getByRole('tab', { name: 'Ярославль' })).toHaveAttribute('aria-selected','true')
    await user.click(screen.getByRole('tab', { name: 'Вологда' }))
    expect(screen.getByRole('link', { name: /Открыть страницу: Демо-пункт выдачи/ })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'На карте: Демо-пункт выдачи' })).toHaveAttribute('aria-pressed', 'true')
    expect(screen.queryByRole('link', { name: /Подробнее:|О магазине/ })).not.toBeInTheDocument()
    expect(screen.getByRole('tab', { name: 'Вологда' })).toHaveAttribute('aria-selected','true')
    expect(screen.getAllByRole('button', { name: 'Выбрать город' })[0]).toHaveTextContent('Вологда')
    expect(screen.queryByRole('radio', { name: /Демо-магазин/ })).not.toBeInTheDocument()
  })

  it('shows an empty state for a site city without contact points', async () => {
    const user = userEvent.setup(); open()
    await user.click(screen.getAllByRole('button', { name: 'Выбрать город' })[0])
    await user.click(screen.getByRole('button', { name: 'Другой город' }))
    expect(screen.getAllByRole('tab').every(tab => tab.getAttribute('aria-selected') === 'false')).toBe(true)
    expect(screen.queryByTestId('contact-point')).not.toBeInTheDocument()
    expect(screen.getByText(/контактные точки пока не указаны/)).toBeInTheDocument()
    expect(screen.queryByRole('radio', { name: /Демо-магазин/ })).not.toBeInTheDocument()
  })

  it.each(contactPoints)('opens $id as a page without changing checkout', async (point) => {
    const user = userEvent.setup()
    localStorage.setItem('garage-checkout-v2', JSON.stringify({ storeId: 'pickup', store: 'Сохранённый пункт заказа', comment: 'Не менять', delivery: 'courier' }))
    open()
    await user.click(screen.getByRole('tab', { name: point.city }))
    const before = localStorage.getItem('garage-checkout-v2')
    expect(screen.queryByRole('radiogroup')).not.toBeInTheDocument()
    const card = screen.getByTestId('contact-point')
    expect(card.querySelector('a a')).toBeNull()
    expect(within(card).getByRole('link', { name: point.phone })).toHaveAttribute('href', `tel:${point.phone.replace(/[^+\d]/g, '')}`)
    expect(within(card).getByRole('link', { name: point.email })).toHaveAttribute('href', `mailto:${point.email}`)
    const trigger = screen.getByRole('link', { name: `Фото и как добраться: ${point.name}` })
    await user.click(trigger)
    expect(screen.getByRole('heading', { level: 1, name: `${point.name} — ${point.city}` })).toBeInTheDocument()
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    await user.click(screen.getByRole('link', { name: 'Вернуться к контактам' }))
    expect(screen.getByRole('tab', { name: point.city })).toHaveAttribute('aria-selected', 'true')
    await user.click(screen.getByRole('link', { name: `Открыть страницу: ${point.name}` }))
    expect(screen.getByRole('heading', { level: 1, name: `${point.name} — ${point.city}` })).toBeInTheDocument()
    expect(localStorage.getItem('garage-checkout-v2')).toBe(before)
  })

  it('validates and completes a demo message without sending personal data', async () => {
    const user = userEvent.setup()
    open()
    await user.click(screen.getByRole('button', { name: 'Написать сообщение' }))
    const dialog = screen.getByRole('dialog', { name: 'Написать сообщение' })
    await user.click(within(dialog).getByRole('button', { name: 'Отправить сообщение' }))
    expect(within(dialog).getByText('Укажите имя')).toBeInTheDocument()
    expect(within(dialog).getByText('Подтвердите согласие на обработку персональных данных')).toBeInTheDocument()
    expect(within(dialog).getByText('Примите пользовательское соглашение')).toBeInTheDocument()
    await user.type(within(dialog).getByLabelText('Ваше имя'), 'Анна')
    await user.click(within(dialog).getByRole('radio', { name: 'Email' }))
    await user.type(within(dialog).getByLabelText('Email для ответа'), 'anna@example.com')
    await user.type(within(dialog).getByLabelText('Сообщение'), 'Нужна консультация по оборудованию')
    const personalData = within(dialog).getByRole('checkbox', { name: /даю согласие на обработку персональных данных/i })
    const agreement = within(dialog).getByRole('checkbox', { name: /принимаю пользовательское соглашение/i })
    expect(within(dialog).getByRole('link', { name: 'Текст согласия' })).toHaveAttribute('href', '/personal-data-consent')
    expect(within(dialog).getByRole('link', { name: 'Политика конфиденциальности' })).toHaveAttribute('target', '_blank')
    await user.click(personalData)
    await user.click(within(dialog).getByRole('button', { name: 'Отправить сообщение' }))
    expect(within(dialog).queryByText('Подтвердите согласие на обработку персональных данных')).not.toBeInTheDocument()
    expect(within(dialog).getByText('Примите пользовательское соглашение')).toBeInTheDocument()
    await user.click(agreement)
    await user.click(within(dialog).getByRole('button', { name: 'Отправить сообщение' }))
    expect(within(dialog).getByRole('status')).toHaveTextContent('Сообщение сохранено в демонстрационном режиме')
  })

  it('reuses the callback form with required name and phone', async () => {
    const user = userEvent.setup()
    open()
    await user.click(screen.getByRole('button', { name: 'Заказать звонок' }))
    const dialog = screen.getByRole('dialog', { name: 'Заказать звонок' })
    await user.click(within(dialog).getByRole('button', { name: 'Отправить запрос' }))
    expect(within(dialog).getByText('Укажите имя')).toBeInTheDocument()
    await user.type(within(dialog).getByLabelText('Ваше имя'), 'Иван')
    await user.type(within(dialog).getByLabelText('Телефон'), '+7 000 000-00-00')
    await user.click(within(dialog).getByRole('button', { name: 'Отправить запрос' }))
    expect(within(dialog).getByText('Подтвердите согласие на обработку персональных данных')).toBeInTheDocument()
    expect(within(dialog).getByText('Примите пользовательское соглашение')).toBeInTheDocument()
    await user.click(within(dialog).getByRole('checkbox', { name: /даю согласие/i }))
    await user.click(within(dialog).getByRole('checkbox', { name: /принимаю пользовательское соглашение/i }))
    await user.click(within(dialog).getByRole('button', { name: 'Отправить запрос' }))
    expect(within(dialog).getByRole('status')).toHaveTextContent('Запрос звонка сохранён в демонстрационном режиме')
  })
})
