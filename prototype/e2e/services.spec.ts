test('rental list and every own detail keep dates, quantity and cart independent',async({page})=>{
  await page.goto('/services/rental')
  const before=await page.evaluate(()=>localStorage.getItem('garage-cart-v2'))
  await page.getByRole('button',{name:/Арендовать: Домкрат/}).click()
  await expect(page.getByRole('dialog')).toContainText('Домкрат подкатной профессиональный')
  await page.keyboard.press('Escape')
  for(const id of ['hydraulic-jack','tool-set','piston-compressor']) {
    await page.locator(`.services-grid a[href="/services/rental/${id}"]`).first().click()
    await expect(page).toHaveURL(new RegExp(`/services/rental/${id}$`))
    await expect(page.locator('main h1')).not.toHaveText('Аренда оборудования и инструментов')
    const heading=await page.locator('main h1').innerText()
    const trigger=page.getByRole('button',{name:'Арендовать',exact:true})
    await trigger.click()
    const dialog=page.getByRole('dialog')
    await expect(dialog).toContainText(heading)
    await contacts(page)
    const [yesterday,today,tomorrow]=await page.evaluate(()=>[-1,0,1].map(offset=>{const d=new Date();d.setDate(d.getDate()+offset);return `${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}`}))
    await page.getByLabel('Дата начала',{exact:true}).fill(yesterday)
    await page.getByLabel('Дата окончания',{exact:true}).fill(today)
    await page.getByLabel('Количество',{exact:true}).fill('1.5')
    await dialog.getByRole('button',{name:'Отправить заявку'}).click()
    await expect(page.getByLabel('Дата начала',{exact:true})).toHaveAttribute('aria-invalid','true')
    await expect(page.getByLabel('Количество',{exact:true})).toHaveAttribute('aria-invalid','true')
    await page.getByLabel('Дата начала',{exact:true}).fill(tomorrow)
    await dialog.getByRole('button',{name:'Отправить заявку'}).click()
    await expect(page.getByLabel('Дата окончания',{exact:true})).toHaveAttribute('aria-invalid','true')
    await page.getByLabel('Дата начала',{exact:true}).fill(today)
    await page.getByLabel('Количество',{exact:true}).fill('2')
    await dialog.getByRole('button',{name:'Отправить заявку'}).click()
    await expect(dialog.getByRole('status')).toHaveText('Заявка на аренду отправлена')
    await expect(dialog).toContainText('не бронь')
    await expect(dialog).toContainText('DEMO-')
    await page.keyboard.press('Escape');await expect(trigger).toBeFocused()
    expect(await page.evaluate(()=>localStorage.getItem('garage-cart-v2'))).toBe(before)
    await page.getByRole('link',{name:'← Все позиции аренды'}).click()
  }
})
for(const width of [360,390,1440]) test(`modal focus, scroll and navigation at ${width}`,async({page})=>{
  await page.setViewportSize({width,height:740});await page.goto('/services/rental/hydraulic-jack')
  const trigger=page.getByRole('button',{name:'Арендовать',exact:true})
  await trigger.click()
  const dialog=page.getByRole('dialog')
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button',{name:'Закрыть форму'})).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button',{name:'Отправить заявку'})).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button',{name:'Закрыть форму'})).toBeFocused()
  expect(await page.evaluate(()=>getComputedStyle(document.body).overflow)).toBe('hidden')
  if(width<768) await expect(page.locator('.mobile-bottom-nav')).toBeHidden()
  const submit=dialog.getByRole('button',{name:'Отправить заявку'})
  await submit.scrollIntoViewIfNeeded()
  const box=(await submit.boundingBox())!
  expect(box.y+box.height).toBeLessThanOrEqual(740)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.keyboard.press('Escape');await expect(trigger).toBeFocused()
  if(width<768) await expect(page.locator('.mobile-bottom-nav')).toBeVisible()
})
