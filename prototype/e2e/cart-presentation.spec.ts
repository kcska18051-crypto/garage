import { expect, test } from '@playwright/test'

for (const width of [360,390,1440,1920]) {
  test.describe(`cart presentation ${width}`, () => {
    test.use({ viewport: { width, height: 900 }, hasTouch: width < 600 })
    test('compact favorites, share layout and related item rails remain functional', async ({ page }) => {
      await page.goto('/profile/favorites')
      const favorites = page.locator('.profile-product-grid--favorites')
      await expect(favorites.locator('article')).toHaveCount(2)
      const card = favorites.locator('article').first()
      const box = await card.boundingBox()
      if (width > 1000) {
        expect(box!.width).toBeLessThanOrEqual(202)
        const grid = await favorites.boundingBox()
        expect(grid!.width).toBeGreaterThan(box!.width * 3)
      }
      await expect(card).toContainText('Артикул:')
      await expect(card.locator('del')).toBeVisible()
      await expect(card.getByRole('link', { name: 'Акция', exact: true })).toBeVisible()
      await card.scrollIntoViewIfNeeded()
      await page.screenshot({ path: `artifacts/refresh-favorites-${width}.png` })
      if ([390,1920].includes(width)) await page.screenshot({ path: `../docs/project-history/screenshots/cart-refresh/favorites-${width}.png` })
      await card.getByRole('button', { name: 'Добавить в корзину', exact: true }).click()
      await card.getByRole('button', { name: 'Удалить из избранного' }).click()
      await expect(favorites.locator('article')).toHaveCount(1)
      await expect(page.locator('.desktop-header a[aria-label="Избранное: 1"]')).toHaveCount(1)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)

      await page.evaluate(() => localStorage.setItem('garage-cart-v2',JSON.stringify([{ id:'product-4',quantity:1 }])))
      await page.goto('/cart')
      const lines = page.getByTestId('cart-line')
      await expect(lines).toHaveCount(1)
      await expect(page.locator('.line-accessories[open]')).toHaveCount(1)
      const summary = page.getByRole('complementary', { name:'Итоги заказа' })
      await expect(summary.getByText('Доставка', { exact:true })).toHaveCount(0)
      await expect(summary).not.toContainText('Рассчитаем при оформлении')
      await expect(summary).toContainText('Наличие и срок получения')
      const total = async () => Number((await summary.locator('.order-summary__total strong').innerText()).replace(/\D/g,''))
      const before = await total()
      const rail = lines.first().locator('.line-accessories__rail')
      await expect(rail.locator('article')).toHaveCount(7)
      if (width < 600) expect(await rail.evaluate(el => el.scrollWidth > el.clientWidth)).toBe(true)
      await rail.getByRole('button', { name:'Добавить Компрессорное масло в корзину' }).click()
      await expect(lines).toHaveCount(2)
      await expect(page.locator('.line-accessories[open]')).toHaveCount(2)
      await lines.filter({ hasText:'SUP-01' }).getByRole('checkbox').check()
      expect(await total()).toBe(before+3900)
      await rail.getByRole('button', { name:'Добавить Компрессорное масло в корзину' }).click()
      await expect(lines).toHaveCount(2)
      expect(await total()).toBe(before+7800)
      await rail.getByRole('button', { name:'Добавить Сервисный фильтр в корзину' }).click()
      await expect(lines).toHaveCount(3)
      await expect(page.locator('.line-accessories[open]')).toHaveCount(1)
      await lines.nth(1).locator('.line-accessories summary').click()
      await expect(page.locator('.line-accessories[open]')).toHaveCount(2)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await lines.first().scrollIntoViewIfNeeded()
      await page.screenshot({ path: `artifacts/refresh-accessories-${width}.png` })
      if ([390,1920].includes(width)) await page.screenshot({ path: `../docs/project-history/screenshots/cart-refresh/accessories-${width}.png` })

      // Browser clipboard API is simulated: no access to the user's system clipboard.
      await page.evaluate(() => Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async (text:string)=>{(window as unknown as {copied:string}).copied=text}}}))
      const trigger = page.getByRole('button', { name:'Поделиться корзиной',exact:true })
      await trigger.click()
      const dialog = page.getByRole('dialog', { name:'Поделиться корзиной' })
      const input = dialog.getByLabel('Ссылка на корзину')
      const url = await input.inputValue()
      await expect(input).toHaveAttribute('readonly','')
      await dialog.getByRole('button', { name:'Копировать ссылку',exact:true }).click()
      await expect(dialog.getByRole('status')).toContainText('Ссылка скопирована')
      expect(await page.evaluate(() => (window as unknown as {copied:string}).copied)).toBe(url)
      if ([390,1920].includes(width)) await page.screenshot({ path: `../docs/project-history/screenshots/cart-refresh/share-${width}.png` })
      await page.evaluate(() => Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async ()=>{throw Error('denied')}}}))
      await dialog.getByRole('button', { name:'Копировать ссылку',exact:true }).click()
      await expect(dialog.getByRole('alert')).toBeVisible()
      await expect(input).toBeFocused()
      expect(await dialog.evaluate(el => el.scrollWidth<=el.clientWidth)).toBe(true)
      const inputBox = await input.boundingBox(), actionsBox=await dialog.locator('.share-cart-dialog__actions').boundingBox()
      expect(actionsBox!.y-(inputBox!.y+inputBox!.height)).toBeGreaterThanOrEqual(15)
      await page.screenshot({ path: `artifacts/refresh-share-${width}.png` })
      await page.keyboard.press('Escape')
      await expect(trigger).toBeFocused()
      // Long but valid shared payload: the URL scrolls inside the field.
      await page.evaluate(() => localStorage.setItem('garage-cart-v2',JSON.stringify(Array.from({length:32},(_,i)=>({id:i===0?'remeza-vk-10-gr-0001':`compressor-${i+1}`,quantity:999})))))
      await page.reload(); await trigger.click()
      expect((await input.inputValue()).length).toBeGreaterThan(1500)
      expect(await dialog.evaluate(el => el.scrollWidth<=el.clientWidth)).toBe(true)
      expect(await page.evaluate(() => document.documentElement.scrollWidth<=innerWidth)).toBe(true)
      await page.keyboard.press('Escape')
      await page.goto('/checkout/review')
      await expect(page.getByRole('complementary',{name:'Итоги заказа'}).getByText('Доставка',{exact:true})).toBeVisible()
    })
  })
}
