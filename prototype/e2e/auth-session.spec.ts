import { expect, test } from '@playwright/test'

async function demoLogin(page: import('@playwright/test').Page) {
  const dialog=page.getByRole('dialog',{name:'Вход и регистрация'})
  await dialog.getByRole('button',{name:'По паролю'}).click()
  await expect(dialog).toContainText('Демонстрационный режим')
  await dialog.getByRole('button',{name:'Войти',exact:true}).click()
  await expect(dialog).toHaveCount(0)
}

for(const width of [360,390,1440,1920]) {
  test.describe(`account auth ${width}`,()=>{
    test.use({viewport:{width,height:900},hasTouch:width<600})
    test('guest, explicit login, reload, logout and checkout intention agree',async({page})=>{
      await page.goto('/profile/data')
      const guest=page.getByRole('region',{name:'Вход в личный кабинет'})
      await expect(guest).toBeVisible()
      await expect(page.getByText('Алексей Смирнов',{exact:true})).toHaveCount(0)
      await expect(page.getByLabel('Имя',{exact:true})).toHaveCount(0)
      await page.screenshot({path:`artifacts/auth-guest-${width}.png`})
      await page.goto('/profile/favorites')
      await page.getByTestId('profile-product-product-1').getByRole('button',{name:'Удалить из избранного'}).click()
      await page.goto('/cart')
      await page.getByTestId('cart-line').first().getByRole('button',{name:'Увеличить количество'}).click()
      const cart=await page.evaluate(()=>localStorage.getItem('garage-cart-v2'))
      const favorites=await page.evaluate(()=>localStorage.getItem('garage-favorites-v1'))
      await page.goto('/profile/data?intent=profile#data')
      await guest.getByRole('button',{name:'Войти / зарегистрироваться'}).click()
      await demoLogin(page)
      await expect(page).toHaveURL(/\/profile\/data\?intent=profile#data$/)
      await expect(page.getByLabel('Имя',{exact:true})).toHaveValue('Алексей')
      await expect(page.getByText('Демо-профиль · телефон подтверждён',{exact:true})).toBeVisible()
      await expect(page.getByRole('button',{name:'Выйти',exact:true})).toHaveCount(1)
      await expect(page.getByRole('button',{name:'Войти / зарегистрироваться'})).toHaveCount(0)
      await page.reload()
      await expect(page.getByLabel('Имя',{exact:true})).toHaveValue('Алексей')
      await page.screenshot({path:`artifacts/auth-member-${width}.png`})
      await page.getByRole('button',{name:'Выйти',exact:true}).click()
      await expect(guest).toBeVisible()
      await expect(page.getByText('Алексей Смирнов',{exact:true})).toHaveCount(0)
      expect(await page.evaluate(()=>localStorage.getItem('garage-cart-v2'))).toBe(cart)
      expect(await page.evaluate(()=>localStorage.getItem('garage-favorites-v1'))).toBe(favorites)
      await page.reload()
      await expect(guest).toBeVisible()
      await expect(page.getByLabel('Имя',{exact:true})).toHaveCount(0)
      expect(await page.evaluate(()=>sessionStorage.getItem('garage-auth-demo-session-v1'))).toBe(null)
      await page.goto('/profile/favorites')
      await expect(page.getByTestId('profile-product-product-1')).toHaveCount(0)
      await expect(page.locator('.profile-product-grid--favorites article')).toHaveCount(1)
      await page.goto('/checkout/review?from=cart#checkout-delivery')
      await expect(page.getByLabel('Подтверждённый телефон',{exact:true})).toHaveCount(0)
      await page.getByLabel('Город самовывоза').selectOption('Вологда')
      await page.getByRole('radio',{name:/Демо-пункт выдачи/}).check()
      await page.getByLabel('СБП',{exact:true}).check()
      await page.getByLabel('Комментарий к заказу').fill('Сохранить выбор после входа')
      await expect(page.getByTestId('checkout-submit')).toHaveAttribute('aria-disabled','true')
      await page.getByRole('button',{name:'Войти или зарегистрироваться'}).click()
      await demoLogin(page)
      await expect(page).toHaveURL(/\/checkout\/review\?from=cart#checkout-delivery$/)
      await expect(page.getByLabel('Город самовывоза')).toHaveValue('Вологда')
      await expect(page.getByRole('radio',{name:/Демо-пункт выдачи/})).toBeChecked()
      await expect(page.getByLabel('СБП',{exact:true})).toBeChecked()
      await expect(page.getByLabel('Комментарий к заказу')).toHaveValue('Сохранить выбор после входа')
      await expect(page.getByTestId('checkout-submit')).toHaveAttribute('aria-disabled','false')
      await expect(page.getByLabel('Подтверждённый телефон',{exact:true})).toHaveAttribute('readonly','')
      expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    })
  })
}
