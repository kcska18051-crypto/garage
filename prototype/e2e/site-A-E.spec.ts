import { expect,test } from '@playwright/test'

for(const width of [360,390,1440,1920]) test.describe(`A-E ${width}`,()=>{
  test.use({viewport:{width,height:900},hasTouch:width<600})
  test('search, existing PDPs, shared properties and selected offers stay connected',async({page,browser})=>{
    test.setTimeout(60000)
    for(const q of ['Remeza','ВК10','GR-0001']) {
      await page.goto(`/search?q=${encodeURIComponent(q)}`)
      await expect(page.locator('.search-results a.product-teaser__name[href="/product/remeza-vk-10-gr-0001"]')).toBeVisible()
      expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    }
    await page.goto('/search?q=нет-такого-demo-запроса')
    await expect(page.getByText('По вашему запросу ничего не найдено')).toBeVisible()
    await page.goto('/')
    await page.getByRole('link',{name:'Открыть товар: Домкрат подкатной профессиональный',exact:true}).first().click()
    await expect(page.getByRole('heading',{level:1,name:'Домкрат подкатной профессиональный'})).toBeVisible()
    await expect(page.getByRole('heading',{level:1,name:'Домкрат подкатной профессиональный'})).toBeInViewport()
    await expect(page.getByRole('complementary',{name:'Покупка товара'})).toContainText('18 900 ₽')
    await page.screenshot({path:`artifacts/A-E-pdp-${width}.png`})
    await page.getByRole('button',{name:'Добавить в корзину',exact:true}).click()
    for(const [id,name] of [['product-2','Набор инструмента для мастерской'],['product-5','Стенд диагностический']]) {
      await page.goto(`/product/${id}`)
      await expect(page.getByRole('heading',{level:1,name})).toBeVisible()
      await expect(page.getByText(/Подробные характеристики пока не предоставлены/)).toBeVisible()
      await page.getByRole('button',{name:'Добавить в корзину',exact:true}).click()
    }
    await page.goto('/cart')
    await expect(page.getByTestId('cart-line')).toHaveCount(3)
    await expect(page.getByTestId('cart-line').filter({hasText:'Домкрат подкатной профессиональный'})).toContainText('GR-0001')
    await page.goto('/product/remeza-vk-10-gr-0001')
    await expect(page.locator('.product-key-specs')).toContainText('10 л/мин')
    await page.getByRole('button',{name:'220 В',exact:true}).click()
    await expect(page.getByRole('heading',{level:1})).not.toContainText('380 В')
    await expect(page.locator('.product-heading')).toContainText('220 В · 5,5 кВт')
    const purchase=page.getByRole('complementary',{name:'Покупка товара'})
    await purchase.getByRole('button',{name:'Увеличить количество'}).click()
    await purchase.getByRole('button',{name:'Коммерческое предложение'}).click()
    const proposal=page.getByRole('dialog',{name:'Коммерческое предложение'})
    await expect(proposal).toContainText('GR-220-55')
    await expect(proposal).toContainText('338 000 ₽')
    await expect(proposal).not.toContainText('380 В')
    await proposal.getByRole('button',{name:'Закрыть коммерческое предложение'}).click()
    await purchase.getByRole('button',{name:'В корзину',exact:true}).click()
    await page.getByRole('button',{name:'В корзину отдельно',exact:true}).first().click()
    await page.getByRole('button',{name:'380 В',exact:true}).click()
    await page.getByRole('button',{name:'7,5 кВт',exact:true}).click()
    await page.getByRole('button',{name:'В корзину отдельно',exact:true}).first().click()
    await page.goto('/cart')
    await expect(page.getByTestId('cart-line').filter({hasText:'GR-220-55'}).filter({hasNotText:'OPT-01'}).getByLabel('Количество',{exact:true})).toHaveText('2')
    const option=page.getByTestId('cart-line').filter({hasText:'OPT-01'})
    await expect(option.locator('.cart-option-link p')).toHaveCount(2)
    await page.getByRole('button',{name:'Поделиться корзиной',exact:true}).click()
    const share=await page.getByLabel('Ссылка на корзину').inputValue()
    const recipient=await browser.newContext()
    try {
      const other=await recipient.newPage();await other.goto(share)
      await other.getByRole('button',{name:'Добавить в мою корзину'}).click();await other.reload()
      await expect(other.getByTestId('cart-line').filter({hasText:'OPT-01'}).locator('.cart-option-link p')).toHaveCount(2)
      await expect(other.locator('.cart-option-link')).toContainText('220 В · 5,5 кВт')
    } finally {await recipient.close()}
    await page.goto('/compare')
    await expect(page.getByRole('row').filter({hasText:'Производительность'}).locator('td').first()).toHaveText('10 л/мин')
    await page.goto('/catalog/compressor-equipment/screw-compressors')
    await page.getByRole('button',{name:'Тег 10 л/мин',exact:true}).click()
    await expect(page.locator('.catalog-results a[href="/product/remeza-vk-10-gr-0001"]').first()).toBeVisible()
    await page.goto('/product/remeza-vk-10-220-55#options')
    await expect(page.locator('#options h2')).toBeInViewport()
    await expect(page.getByRole('button',{name:'220 В',exact:true})).toHaveAttribute('aria-pressed','true')
    await page.reload()
    await expect(page.locator('#options h2')).toBeInViewport()
    await page.locator('.product-anchor-nav a[href="#characteristics"]').click()
    await expect(page.locator('#characteristics h2')).toBeInViewport()
    await page.goto('/product/not-a-real-sku')
    await expect(page.getByRole('heading',{name:'Страница не найдена'})).toBeVisible()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  })
})
