import {test,expect} from '@playwright/test'
test.beforeEach(async({page})=>{await page.route('**/garage/style-check/**',route=>route.continue({url:route.request().url().replace('/garage/style-check/','/style-check/')}))})
for(const width of [1440,390])test(`document request with selected offer at ${width}`,async({page})=>{
 await page.setViewportSize({width,height:900})
 await page.addInitScript(()=>{localStorage.setItem('garage-region-v1','Ярославль');localStorage.setItem('garage-cookie-preference',JSON.stringify({version:2,choice:'necessary'}))})
 await page.goto('/product/remeza-vk-10-gr-0001')
 const aside=page.getByRole('complementary',{name:'Документы и гарантия'})
 await aside.getByRole('button',{name:'Запросить документы'}).click()
 const dialog=page.getByRole('dialog',{name:'Запросить документы'})
 await expect(dialog.getByLabel('Выбранный товар')).toHaveValue(/GR-0001/)
 await dialog.getByLabel('Ваше имя').fill('Мария')
 await dialog.getByLabel('Телефон или электронная почта').fill('client@example.ru')
 for(const box of await dialog.getByRole('checkbox').all())await box.check()
 await dialog.getByRole('button',{name:'Отправить запрос'}).click()
 await expect(dialog.getByRole('status')).toContainText('Запрос принят')
 await dialog.getByRole('button',{name:'Закрыть',exact:true}).click()
 await expect(dialog).toHaveCount(0)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.locator('#documents').getByRole('button',{name:'Паспорт изделия Запросить копию'}).click()
 await expect(page.getByLabel('Комментарий (необязательно)')).toHaveValue('Паспорт изделия')
 await page.keyboard.press('Escape')
 await expect(page.getByRole('dialog',{name:'Запросить документы'})).toHaveCount(0)
})
