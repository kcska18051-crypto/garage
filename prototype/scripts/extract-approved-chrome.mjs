import fs from 'node:fs'
import postcss from 'postcss'

// Copy only the approved navigation and footer rules, preserving their cascade.
// Page rules and root tokens stay exclusive to the approved homepage.
const source = fs.readFileSync('src/app/approvedHomepage.tsx', 'utf8')
const files = [...source.matchAll(/'\/garage\/style-check\/([^'?]+\.css)/g)].map(match => match[1])
const chrome = /\.(?:site-header|site-footer|style-check-footer|footer-[\w-]+|logo|catalog-button|search-box[\w-]*|header-action[\w-]*|desktop-header[\w-]*|mobile-header[\w-]*|mobile-bottom-nav[\w-]*|third-level-nav[\w-]*|paint-service-link[\w-]*|service-link|service-row|reference-(?:mobile[\w-]*|bottom[\w-]*|back-to-top|desktop-services|compact-contact|contact-tile|geo|city-chevron|callback)|review-mobile[\w-]*|style-check-header-symbol[\w-]*)\b/
const prefix = '.app-shell[data-style-check]'
const output = postcss.root()
for (const file of files) {
  const root = postcss.parse(fs.readFileSync(`public/style-check/${file}`, 'utf8'))
  root.walkComments(comment => comment.remove())
  root.walkRules(rule => {
    const selectors = rule.selectors.filter(selector => selector.startsWith(prefix) && chrome.test(selector) && !/(?:^|[ >])main(?:[ .:#>]|$)|\.review-home|\.product-showcase|\.hero\b|\.brand-grid/.test(selector))
    if (!selectors.length) rule.remove()
    else rule.selectors = selectors.map(selector => selector.replaceAll(prefix, '.app-shell[data-approved-chrome]'))
  })
  root.walkAtRules(rule => { if (!['media', 'supports', 'container'].includes(rule.name)) rule.remove() })
  root.walkAtRules(rule => { if (!rule.nodes?.length) rule.remove() })
  output.append(root.nodes)
}
const tokens = `.app-shell[data-approved-chrome] :is(.site-header,.site-footer,.mobile-bottom-nav) { --gutter: 24px; --brand-yellow: #ffcc00; --brand-red: #c92f29; --brand-ink: #171717; --color-background: #fff; --color-surface: #fff; --color-border: #deded8; --color-text: #171717; --color-text-muted: #595954; --color-placeholder-1: #f5f5f2; --color-focus: #9a6500; --color-accent: #c92f29; }\n`
fs.writeFileSync('public/style-check/approved-chrome.css', '/* Generated by scripts/extract-approved-chrome.mjs. */\n' + tokens + output.toString() + '\n@media(max-width:767px) { .app-shell[data-approved-chrome] :is(.site-header,.site-footer,.mobile-bottom-nav) { --gutter: 12px; } }\n')
console.log(`Extracted shared header and footer styles from ${files.length} approved stylesheets`)
